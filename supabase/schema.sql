-- Creates every table. Run in the Supabase SQL editor.
create table if not exists universities (
  id bigint generated always as identity primary key,
  name text not null,
  country text not null,
  city text,
  region text not null,
  lat double precision,
  lng double precision,
  currency_code text not null,
  region_band_min numeric,
  region_band_max numeric
);

create table if not exists smu_modules (
  id bigint generated always as identity primary key,
  code text not null unique,
  name text not null
);

create table if not exists credit_mappings (
  id bigint generated always as identity primary key,
  university_id bigint not null references universities(id) on delete cascade,
  smu_module_id bigint not null references smu_modules(id) on delete cascade,
  foreign_course_code text,
  foreign_course_name text not null,
  notes text
);

create table if not exists shortlists (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  university_id bigint not null references universities(id) on delete cascade,
  unique (user_id, university_id)
);

create table if not exists schedule_blocks (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  university_id bigint not null references universities(id) on delete cascade,
  module_name text not null,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  start_time time not null,
  end_time time not null
);

create table if not exists reviews (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  university_id bigint not null references universities(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now()
);

-- for cost and budgetting 
CREATE TABLE IF NOT EXISTS public.university_costs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id BIGINT NOT NULL
        REFERENCES public.universities(id) ON DELETE CASCADE,
    category TEXT NOT NULL,
    amount_min NUMERIC(12,2) NOT NULL CHECK (amount_min >= 0),
    amount_max NUMERIC(12,2) NOT NULL CHECK (amount_max >= amount_min),
    currency_code TEXT NOT NULL,
    period TEXT NOT NULL CHECK (
        period IN ('monthly', 'annual', 'semester', 'one_time', 'nine_months')
    ),
    source_name TEXT NOT NULL,
    source_url TEXT NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.user_budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    university_id BIGINT NOT NULL
        REFERENCES public.universities(id) ON DELETE CASCADE,
    duration_months INTEGER NOT NULL
        CHECK (duration_months BETWEEN 1 AND 12),
    currency_code TEXT NOT NULL,
    accommodation_budget NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (accommodation_budget >= 0),
    food_budget NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (food_budget >= 0),
    transport_budget NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (transport_budget >= 0),
    personal_budget NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (personal_budget >= 0),
    other_budget NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (other_budget >= 0),
    total_budget NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (total_budget >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);